val LocalSilencerStrings = staticCompositionLocalOf { englishStrings }

fun stringsFor(language: AppLanguage): SilencerStrings {
    return when (language.effective()) {
        AppLanguage.Chinese -> chineseStrings
        AppLanguage.English -> englishStrings
        AppLanguage.System -> englishStrings
    }
}

